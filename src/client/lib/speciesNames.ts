/**
 * Hands out species names in a shuffled order without repeating until all 100
 * have been used (a sender never has more than 3 receivers at once).
 */
export function createNamePicker(random: () => number = Math.random): () => string {
  const shuffled = (): string[] => {
    const names = [...SPECIES_NAMES];
    for (let i = names.length - 1; i > 0; i -= 1) {
      const j = Math.floor(random() * (i + 1));
      [names[i], names[j]] = [names[j]!, names[i]!];
    }
    return names;
  };
  let queue = shuffled();
  return () => {
    if (queue.length === 0) queue = shuffled();
    return queue.pop()!;
  };
}
